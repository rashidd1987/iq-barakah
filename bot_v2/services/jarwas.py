LEVEL_ORDER = ["А", "Б", "В", "Г"]
LEVEL_FULL_NAMES = {
    "А": "ВАКТ · Тайм-менеджмент мусульманина",
    "Б": "Сезон 1 · Основание",
    "В": "Сезон 2 · Строительство",
    "Г": "Сезон 3 · Наследие",
}

MAX_HISTORY = 6


def setup_jarwas(api_key: str):
    global _client
    if api_key:
        _client = anthropic.AsyncAnthropic(api_key=api_key)


def check_daily_limit(user_id: int) -> bool:
    """Возвращает True если лимит НЕ исчерпан (можно отвечать)."""
    today = str(date.today())
    entry = _daily_usage.get(user_id)
    if entry is None or entry[0] != today:
        _daily_usage[user_id] = (today, 0)
        entry = _daily_usage[user_id]
    return entry[1] < DAILY_LIMIT


def increment_daily_usage(user_id: int):
    today = str(date.today())
    entry = _daily_usage.get(user_id)
    if entry is None or entry[0] != today:
        _daily_usage[user_id] = (today, 1)
    else:
        _daily_usage[user_id] = (today, entry[1] + 1)


def build_jarwas_system(
    level: str | None,
    week: int | None,
    user_profile: dict | None = None,
) -> str:
    """Персонализированный system prompt с контекстом уровня и профиля."""
    if not level or level not in LEVEL_ORDER:
        context = (
            "\n\nКОНТЕКСТ УЧАСТНИКА:\n"
            "Этот человек ещё не начал программу или только знакомится с ней.\n"
            "Ты можешь рассказать о структуре программы в целом и помочь выбрать с чего начать.\n"
            "Детали конкретных уроков не раскрывай — пусть открываются в процессе."
        )
    else:
        idx = LEVEL_ORDER.index(level)
        current_name = LEVEL_FULL_NAMES[level]
        passed = [LEVEL_FULL_NAMES[l] for l in LEVEL_ORDER[:idx]]
        ahead = [LEVEL_FULL_NAMES[l] for l in LEVEL_ORDER[idx + 1:]]

        context = (
            f"\n\nКОНТЕКСТ УЧАСТНИКА:\n"
            f"Сейчас проходит: {current_name}, неделя {week}.\n"
        )
        if passed:
            context += f"Уже прошёл: {', '.join(passed)}.\n"
        if ahead:
            context += (
                f"Впереди: {', '.join(ahead)} — но детали этих курсов НЕ раскрывай.\n"
                "Если спрашивает про будущие уровни — скажи тепло: "
                "«Это ждёт тебя впереди — сначала давай закрепим то что ты проходишь сейчас 🌿»\n"
            )
        context += (
            f"Твоя задача — помогать участнику именно с его текущим уровнем ({current_name}) "
            f"и не забегать вперёд."
        )

    if user_profile:
        DIAG_LABELS = {
            "А": "Начинающий", "Б": "Развивающийся",
            "В": "Устойчивый", "В+": "Лидер (Джамаат)",
        }
        lines = []
        name = (user_profile.get("name") or "").split()[0]
        if name:
            lines.append(f"Имя: {name}")
        occupation = user_profile.get("occupation", "")
        if occupation:
            lines.append(f"Деятельность: {occupation}")
        age = user_profile.get("age", "")
        if age:
            lines.append(f"Возраст: {age}")
        diag_lv = user_profile.get("diag_level", "")
        if diag_lv:
            label = DIAG_LABELS.get(diag_lv, diag_lv)
            lines.append(f"Результат диагностики: {label} ({diag_lv})")
        is_female = user_profile.get("is_female")
        if is_female is not None:
            lines.append(f"Пол: {'женский' if is_female else 'мужской'}")
        if lines:
            context = "\n\nПРОФИЛЬ УЧАСТНИКА:\n" + "\n".join(lines) + "\n" + context

    return JARWAS_SYSTEM + context


import logging as _logging
_log = _logging.getLogger(__name__)

JARWAS_MODEL = "claude-sonnet-4-6"


async def ask_jarwas(
    history: list[dict],
    user_message: str,
    level: str | None = None,
    week: int | None = None,
    user_profile: dict | None = None,
) -> str:
    if not _client:
        return "Джарвас временно недоступен. Напишите куратору. 🤍"

    system = build_jarwas_system(level, week, user_profile)
    history = history[-MAX_HISTORY:]
    messages = history + [{"role": "user", "content": user_message}]

    try:
        response = await _client.messages.create(
            model=JARWAS_MODEL,
            max_tokens=1024,
            system=[{"type": "text", "text": system, "cache_control": {"type": "ephemeral"}}],
            messages=messages,
        )
        return response.content[0].text
    except Exception as e:
        _log.error("Jarwas API error: %s: %s", type(e).__name__, e)
        return f"⚠️ Ошибка Джарваса: {type(e).__name__}: {str(e)[:200]}"


