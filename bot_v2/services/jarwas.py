MAX_HISTORY = 10


def _gender_block(is_female: bool | None) -> str | None:
    if is_female is True:
        return (
            "Участница — ЖЕНЩИНА. Обращайся к ней «Сестра». "
            "Используй женские окончания во всех глаголах и прилагательных: "
            "«готова», «сделала», «молодец», «рада», «уверена», «терпелива» и т.д."
        )
    elif is_female is False:
        return (
            "Участник — МУЖЧИНА. Обращайся к нему «Брат». "
            "Используй мужские окончания: "
            "«готов», «сделал», «молодец», «рад», «уверен», «терпелив» и т.д."
        )
    return None


def setup_jarwas(api_key: str):
    global _client
    if api_key:
        _client = anthropic.AsyncAnthropic(api_key=api_key)


async def ask_jarwas(
    history: list[dict],
    user_message: str,
    is_female: bool | None = None,
) -> str:
    if not _client:
        return "Джарвас временно недоступен. Напишите куратору. 🤍"

    history = history[-MAX_HISTORY:]
    messages = history + [{"role": "user", "content": user_message}]

    system: list[dict] = [
        {"type": "text", "text": JARWAS_SYSTEM, "cache_control": {"type": "ephemeral"}}
    ]
    gender_text = _gender_block(is_female)
    if gender_text:
        system.append({"type": "text", "text": gender_text})

    try:
        response = await _client.messages.create(
            model="claude-opus-4-5",
            max_tokens=512,
            system=system,
            messages=messages,
        )
        return response.content[0].text
    except Exception as e:
        import logging
        logging.getLogger(__name__).error("Jarwas API error: %s", e)
        return "Джарвас сейчас перегружен. Попробуй чуть позже или напиши куратору. 🤍"


def parse_btn_marker(text: str) -> tuple[str, str | None]:
    """Возвращает (clean_text, btn_type | None)."""
    lines = text.strip().split("\n")
    last = lines[-1].strip()
    markers = {"[BTN:diag]", "[BTN:buy_vakt]", "[BTN:buy_s1]", "[BTN:curator]"}
    if last in markers:
        btn = last[5:-1]
        return "\n".join(lines[:-1]).strip(), btn
    return text, None
