def get_test(track: str, step: int, skill_level: str) -> list[dict]:
    """
    Вернуть список вопросов для шага.
    track: "А" = ВАКТ, "Б" = Сезон 1, и т.д.
    step: номер шага (1-based)
    skill_level: "I", "II", "III"
    """
    if track == "А":
        step_tests = VAKT_TESTS.get(step, {})
        questions = step_tests.get(skill_level, step_tests.get("I", []))
        return questions
    # Будущие треки добавляются здесь
    return []


def format_question(q: dict, idx: int) -> str:
    """Форматировать вопрос для отправки в Telegram."""
    opts = "\n".join(
        f"{'🔘' if i == q['correct'] else '⚪'} {chr(65+i)}) {o}"
        for i, o in enumerate(q["opts"])
    )
    return f"*Вопрос {idx + 1}:* {q['q']}\n\n{opts}"
