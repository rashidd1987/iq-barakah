def get_test(track: str, step: int, skill_level: str) -> list[dict]:
    """
    Вернуть список вопросов для шага.
    track: "А" = ВАКТ (шаги 1-6), "Б" = Сезон 1 (шаги 1-8), "В" = Сезон 2 (шаги 1-8), "Г" = Сезон 3 (шаги 1-8)
    step: номер шага внутри трека (1-based)
    skill_level: "I", "II", "III"
    """
    if track == "А":
        source = VAKT_TESTS
        key = step
    elif track == "Б":
        source = IQ_S1_TESTS
        key = step
    elif track == "В":
        source = IQ_S2_TESTS
        key = step + 8  # Сезон 2: шаги 9-16 в словаре
    elif track == "Г":
        source = IQ_S3_TESTS
        key = step + 16  # Сезон 3: шаги 17-24 в словаре
    else:
        return []

    step_tests = source.get(key, {})
    return step_tests.get(skill_level, step_tests.get("I", []))


def format_question(q: dict, idx: int) -> str:
    """Форматировать вопрос для отправки в Telegram."""
    opts = "\n".join(
        f"{'🔘' if i == q['correct'] else '⚪'} {chr(65+i)}) {o}"
        for i, o in enumerate(q["opts"])
    )
    return f"*Вопрос {idx + 1}:* {q['q']}\n\n{opts}"
