async def send_week_lesson(bot, user_id: int, entry: dict, ctx=None):
    """Отправить урок недели конкретному пользователю."""
    level = entry["level"]
    week_idx = entry["week"] - 1
    lessons = PROGRAM.get(level, [])
    if week_idx >= len(lessons):
        return

    lesson = lessons[week_idx]
    name = entry.get("name", "Брат")
    title = lesson["title"]
    total = LEVEL_WEEKS[level]

    # Текст урока: для ВАКТ (уровень А) — берём текст по vakt_level участника
    raw_text = lesson["text"]
    if isinstance(raw_text, dict):
        vakt_level = entry.get("vakt_level", "А")
        text = raw_text.get(vakt_level, raw_text.get("А", ""))
    else:
        text = raw_text.replace("{name}", name.split()[0] if name else "Брат")

    # Задания: для ВАКТ — показываем только задания уровня участника
    raw_tasks = lesson["tasks"]
    if isinstance(raw_tasks, dict):
        if level == "А" and entry.get("vakt_level"):
            # ВАКТ: только задания выбранного уровня
            vakt_level = entry.get("vakt_level", "А")
            level_tasks = raw_tasks.get(vakt_level, [])
            tasks = "\n".join(f"  {t}" for t in level_tasks)
        else:
            # Другие уровни: показываем все три
            labels = {"А": "🌱 Уровень А", "Б": "📗 Уровень Б", "В": "📘 Уровень В"}
            tasks_parts = []
            for key, label in labels.items():
                lvl_tasks = raw_tasks.get(key, [])
                if lvl_tasks:
                    tasks_parts.append(
                        f"*{label}:*\n" + "\n".join(f"  {t}" for t in lvl_tasks)
                    )
            tasks = "\n\n".join(tasks_parts)
    else:
        tasks = "\n".join(f"  {t}" for t in raw_tasks)

    msg = (
        f"📅 *{title}*\n"
        f"_{LEVEL_NAMES[level]} · Неделя {entry['week']} из {total}_\n\n"
        f"{text}\n\n"
        f"*Задания на эту неделю:*\n{tasks}"
    )
    map_url = f"{MINIAPP_URL}?lvl={level}&wk={entry['week']}"

    # Видео для урока
    video_val = get_lesson_video(ctx, level, entry["week"]) if ctx else None
    audio_val = get_lesson_audio(ctx, level, entry["week"]) if ctx else None

    try:
        # 1. Видео
        if video_val:
            if video_val.startswith("http"):
                await bot.send_message(
                    chat_id=user_id,
                    text=f"🎬 *Видео-урок — Неделя {entry['week']}*\n\n{video_val}",
                    parse_mode="Markdown",
                    disable_web_page_preview=False,
                )
            else:
                await bot.send_video(
                    chat_id=user_id,
                    video=video_val,
                    caption=f"🎬 *Видео-урок — Неделя {entry['week']}*",
                    parse_mode="Markdown",
                )

        # 2. Голосовое (для тех кто слушает в дороге)
        if audio_val:
            await bot.send_voice(
                chat_id=user_id,
                voice=audio_val,
                caption="🎙 *Аудио-версия* — слушай где удобно",
                parse_mode="Markdown",
            )

        # Для ВАКТ (уровень А) — кнопка разблокировки следующей недели
        if level == "А":
            action_btn = InlineKeyboardButton("✅ Выполнил задания — открыть следующую неделю", callback_data="week_ack")
        else:
            action_btn = InlineKeyboardButton("✅ Понял, иду делать", callback_data="week_ack")

        await bot.send_message(
            chat_id=user_id,
            text=msg,
            parse_mode="Markdown",
            reply_markup=InlineKeyboardMarkup([
                [InlineKeyboardButton("📱 Открыть карту пути", web_app=WebAppInfo(url=map_url))],
                [action_btn],
            ])
        )
    except Exception as e:
        logger.warning(f"Не удалось отправить урок пользователю {user_id}: {e}")


