def get_pairs(ctx: ContextTypes.DEFAULT_TYPE) -> dict:
    """bot_data['pairs'] = {uid: partner_uid, ...} — двусторонний словарь."""
    return ctx.bot_data.setdefault("pairs", {})


async def auto_pair(bot, uid: int, ctx) -> bool:
    """Автоматически ищет свободного партнёра того же пола и уровня.
    Парит ТОЛЬКО если пол известен у обоих и совпадает. Возвращает True если пара найдена."""
    uid_str = str(uid)
    pairs = get_pairs(ctx)
    if uid_str in pairs:
        return False  # уже есть пара

    genders   = ctx.bot_data.get("user_genders", {})
    active    = get_active_users(ctx)
    names     = ctx.bot_data.get("user_names", {})
    usernames = ctx.bot_data.get("user_usernames", {})

    is_female = genders.get(uid_str)
    if is_female is None:
        return False  # пол неизвестен — не паровать

    my_level = active.get(uid_str, {}).get("level")

    # Ищем активного участника без пары: строго тот же пол + тот же уровень
    partner_id = None
    for pid_str, entry in active.items():
        if pid_str == uid_str:
            continue
        if pid_str in pairs:
            continue
        p_gender = genders.get(pid_str)
        if p_gender is None or p_gender != is_female:
            continue
        if my_level and entry.get("level") != my_level:
            continue
        partner_id = int(pid_str)
        break

    if not partner_id:
        return False

    # Назначаем пару двусторонне
    pairs[uid_str] = partner_id
    pairs[str(partner_id)] = uid

    name1    = names.get(uid_str, "Участник")
    name2    = names.get(str(partner_id), "Участник")
    link1    = _user_link(uid, name1, usernames.get(uid_str))
    link2    = _user_link(partner_id, name2, usernames.get(str(partner_id)))
    word     = lambda f: "якорная сестра" if f else "якорный брат"

    msg = (
        "🤝 *{title} назначен{a}!*\n\n"
        "👤 {link}\n\n"
        "📋 *Правила:*\n"
        "• Пиши каждую пятницу — как дела, как практики\n"
        "• Делай дуа за него/неё по имени\n"
        "• Поддерживай — не осуждай\n\n"
        "🌿 _Баракат приходит через связь_"
    )

    await bot.send_message(
        uid,
        msg.format(
            title=word(is_female).capitalize(),
            a="а" if is_female else "",
            link=link2
        ),
        parse_mode="Markdown",
        disable_web_page_preview=True
    )
    p_female = genders.get(str(partner_id))
    await bot.send_message(
        partner_id,
        msg.format(
            title=word(p_female).capitalize(),
            a="а" if p_female else "",
            link=link1
        ),
        parse_mode="Markdown",
        disable_web_page_preview=True
    )
    return True


def _user_link(uid: int, name: str, username: str | None) -> str:
    if username:
        return f"[{name}](https://t.me/{username})"
    return f"[{name}](tg://user?id={uid})"


async def cmd_pair(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    """Только для кураторов. /pair <uid1> <uid2> — создать пару."""
    if update.effective_user.id not in CURATOR_IDS:
        await update.message.reply_text("⛔️ Команда только для кураторов.")
        return

    args = ctx.args
    if len(args) < 2:
        await update.message.reply_text(
            "Использование: `/pair <user_id_1> <user_id_2>`\n\n"
            "Пример: `/pair 111222333 444555666`",
            parse_mode="Markdown"
        )
        return

    try:
        uid1, uid2 = int(args[0]), int(args[1])
    except ValueError:
        await update.message.reply_text("❌ Оба аргумента должны быть числами (user_id).")
        return

    if uid1 == uid2:
        await update.message.reply_text("❌ Нельзя соединить пользователя с самим собой.")
        return

