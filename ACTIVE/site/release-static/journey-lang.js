var JOURNEY_SOURCE_LANG = 'ru';
var JOURNEY_LANGS = ['ru','en','ar','tr'];
var JOURNEY_TEXT_NODES = [];
var JOURNEY_OBSERVER_LOCK = false;

function journeyEnsureSwitcher(){
  // Language switcher removed — site is Russian-only
}

function journeyApplyStaticLabels(lang){
  var dict = window.JOURNEY_I18N[lang] || window.JOURNEY_I18N.ru;
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var value = dict[el.dataset.i18n];
    if(value) el.textContent = value;
  });
}

function journeyNormalizeText(value){
  return (value || '').replace(/\s+/g, ' ').trim();
}

function journeyShouldTranslateNode(node){
  var parent = node && node.parentElement;
  if (!parent) return false;
  var text = journeyNormalizeText(node.nodeValue);
  if (!text) return false;
  var tag = parent.tagName;
  if (['SCRIPT','STYLE','NOSCRIPT','TEXTAREA','INPUT','SELECT','OPTION','SVG','CANVAS'].indexOf(tag) !== -1) return false;
  if (parent.closest && parent.closest('[data-no-i18n], [data-i18n], script, style, svg, canvas')) return false;
  return true;
}

function journeyCollectTextNodes(){
  JOURNEY_TEXT_NODES = [];
  if (!document.body || !window.NodeFilter) return;
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: function(node){
      return journeyShouldTranslateNode(node) ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  var node;
  while ((node = walker.nextNode())) {
    if (!node.__journeyOriginal) node.__journeyOriginal = node.nodeValue;
    JOURNEY_TEXT_NODES.push(node);
  }
}

function journeyApplyTextPattern(lang, key){
  var groups = window.JOURNEY_TEXT_PATTERNS || {};
  var patterns = groups[lang] || [];
  for (var i = 0; i < patterns.length; i += 1) {
    var pattern = patterns[i][0];
    var replacement = patterns[i][1];
    if (pattern.test(key)) return key.replace(pattern, replacement);
  }
  return '';
}

function journeyPostProcessTranslation(lang, value){
  if (lang === 'ru' || !value) return value;
  return value
    .replace(/(\d+(?:[.,]\d+)?)\s*тыс(?=\s|$)/g, '$1K')
    .replace(/(\d+(?:[.,]\d+)?)\s*млн\s*₽/g, '$1M ₽')
    .replace(/(\d+(?:[.,]\d+)?)\s*месяц(?:а|ев)?(?=\s|$)/g, '$1 month')
    .replace(/Мамедова Мерджанат Магомедовна/g, 'Mamedova Merdzhanat Magomedovna')
    .replace(/ИП\s+/g, 'Individual Entrepreneur ');
}

function journeyResolveTranslation(lang, key){
  var dictionaries = window.JOURNEY_TEXT_I18N || {};
  var dict = dictionaries[lang] || {};
  var translated = lang === 'ru' ? key : dict[key];
  if (!translated && lang !== 'ru') translated = journeyApplyTextPattern(lang, key);
  if (!translated && lang !== 'ru' && dictionaries.en) translated = dictionaries.en[key] || journeyApplyTextPattern('en', key);
  return journeyPostProcessTranslation(lang, translated || '');
}

function journeyApplyDocumentMeta(lang){
  if (!document.__journeyOriginalTitle) document.__journeyOriginalTitle = document.title;
  var title = journeyResolveTranslation(lang, journeyNormalizeText(document.__journeyOriginalTitle));
  if (title) document.title = title;

  document.querySelectorAll('meta[name="description"], meta[property="og:title"], meta[property="og:description"], meta[name="twitter:title"], meta[name="twitter:description"]').forEach(function(meta){
    if (!meta.__journeyOriginalContent) meta.__journeyOriginalContent = meta.getAttribute('content') || '';
    var value = journeyResolveTranslation(lang, journeyNormalizeText(meta.__journeyOriginalContent));
    if (value) meta.setAttribute('content', value);
  });
}

function journeyApplyTextDictionary(lang){
  JOURNEY_OBSERVER_LOCK = true;
  JOURNEY_TEXT_NODES.forEach(function(node){
    var original = node.__journeyOriginal || node.nodeValue;
    var key = journeyNormalizeText(original);
    var translated = journeyResolveTranslation(lang, key);
    if (!translated) return;
    var leading = (original.match(/^\s*/) || [''])[0];
    var trailing = (original.match(/\s*$/) || [''])[0];
    var nextValue = leading + translated + trailing;
    if (node.nodeValue !== nextValue) node.nodeValue = nextValue;
  });
  journeyApplyDocumentMeta(lang);
  JOURNEY_OBSERVER_LOCK = false;
}

function journeyRefreshTextDictionary(lang){
  journeyCollectTextNodes();
  journeyApplyTextDictionary(lang);
}

function journeyMarkActiveLang(lang){
  document.querySelectorAll('.lang-btn,.journey-lang-floating button').forEach(function(btn){
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function setJourneyLang(lang, options){
  options = options || {};
  if (JOURNEY_LANGS.indexOf(lang) === -1) lang = 'ru';

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  localStorage.setItem('iq_journey_lang', lang);
  journeyMarkActiveLang(lang);
  journeyApplyStaticLabels(lang);
  journeyApplyTextDictionary(lang);
  if (typeof window.applyJourneyPageLang === 'function') {
    window.applyJourneyPageLang(lang);
  }
}

window.setJourneyLang = setJourneyLang;

function journeyBindLanguageButtons(){
  document.querySelectorAll('[data-lang]').forEach(function(btn){
    if (btn.dataset.langBound === '1') return;
    btn.dataset.langBound = '1';
    btn.addEventListener('click', function(event){
      event.preventDefault();
      setJourneyLang(btn.dataset.lang);
    });
  });
}

window.addEventListener('storage', function(event){
  if (event.key === 'iq_journey_lang' && event.newValue) {
    setJourneyLang(event.newValue);
  }
});

(function(){
  function boot(){
    var storedLang = localStorage.getItem('iq_journey_lang');
    var lang = storedLang || 'ru';
    journeyEnsureSwitcher();
    journeyBindLanguageButtons();
    journeyCollectTextNodes();
    setJourneyLang(lang, { noReload: true });
    window.addEventListener('resize', journeyEnsureSwitcher, { passive: true });
    if (window.MutationObserver) {
      var timer;
      new MutationObserver(function(){
        if (JOURNEY_OBSERVER_LOCK) return;
        clearTimeout(timer);
        timer = setTimeout(function(){
          journeyRefreshTextDictionary(localStorage.getItem('iq_journey_lang') || 'ru');
          journeyBindLanguageButtons();
        }, 80);
      }).observe(document.body, { childList: true, subtree: true });
    }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();
})();
